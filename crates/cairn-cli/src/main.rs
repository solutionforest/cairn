#![forbid(unsafe_code)]
#![warn(clippy::all)]
//! `cairn` binary: `init`, `serve`, `config check`.

use anyhow::Context as _;
use cairn_core::Config;
use clap::{Parser, Subcommand, ValueEnum};
use rand::Rng as _;
use std::path::{Path, PathBuf};

#[derive(Parser)]
#[command(
    name = "cairn",
    version,
    about = "Cairn: an S3-compatible object store"
)]
struct Cli {
    /// Log output format.
    #[arg(long, global = true, value_enum, default_value_t = LogFormat::Text)]
    log_format: LogFormat,
    #[command(subcommand)]
    cmd: Cmd,
}

#[derive(Clone, Copy, ValueEnum)]
enum LogFormat {
    Text,
    Json,
}

#[derive(Subcommand)]
enum Cmd {
    /// Create a data directory, a `cairn.toml` and root credentials (printed once).
    Init {
        /// Data directory to create.
        #[arg(long)]
        data_dir: PathBuf,
        /// Listen address written to the config.
        #[arg(long, default_value = "127.0.0.1:9000")]
        listen: String,
    },
    /// Run the server.
    Serve {
        /// Path to `cairn.toml` (`CAIRN_*` environment variables override it).
        #[arg(long, short, env = "CAIRN_CONFIG")]
        config: Option<PathBuf>,
    },
    /// Configuration utilities.
    Config {
        #[command(subcommand)]
        cmd: ConfigCmd,
    },
}

#[derive(Subcommand)]
enum ConfigCmd {
    /// Validate a config file and print the effective configuration with secrets masked.
    Check {
        /// Path to `cairn.toml`.
        #[arg(long, short, env = "CAIRN_CONFIG")]
        config: Option<PathBuf>,
    },
}

fn init_tracing(format: LogFormat, level: &str) {
    let filter = tracing_subscriber::EnvFilter::try_from_default_env()
        .unwrap_or_else(|_| tracing_subscriber::EnvFilter::new(level));
    let b = tracing_subscriber::fmt().with_env_filter(filter);
    match format {
        LogFormat::Json => b.json().init(),
        LogFormat::Text => b.init(),
    }
}

fn random_string(len: usize, alphabet: &[u8]) -> String {
    let mut rng = rand::rng();
    (0..len)
        .map(|_| alphabet[rng.random_range(0..alphabet.len())] as char)
        .collect()
}

/// Root credentials in the shapes DESIGN §8.1 describes (`CAIRN…` 20-char key id).
fn generate_root_credentials() -> (String, String) {
    const UPPER: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZ234567";
    const SECRET: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    (
        format!("CAIRN{}", random_string(15, UPPER)),
        random_string(40, SECRET),
    )
}

fn init(data_dir: &Path, listen: &str) -> anyhow::Result<PathBuf> {
    let cfg_path = data_dir.join("cairn.toml");
    anyhow::ensure!(
        !cfg_path.exists(),
        "{} already exists; refusing to overwrite it",
        cfg_path.display()
    );
    for d in ["meta", "blobs", "tmp", "keys"] {
        std::fs::create_dir_all(data_dir.join(d))
            .with_context(|| format!("creating {}", data_dir.join(d).display()))?;
    }
    let data_dir = data_dir
        .canonicalize()
        .with_context(|| format!("resolving {}", data_dir.display()))?;
    let env_ak = std::env::var("CAIRN_ROOT_ACCESS_KEY").ok();
    let env_sk = std::env::var("CAIRN_ROOT_SECRET").ok();
    let (ak, sk, generated) = match (env_ak, env_sk) {
        (Some(a), Some(s)) => (a, s, false),
        _ => {
            let (a, s) = generate_root_credentials();
            (a, s, true)
        }
    };
    let mut cfg = Config::default();
    cfg.server.listen = listen.to_string();
    cfg.storage.data_dir = data_dir.clone();
    cfg.auth.root_access_key = Some(ak.clone());
    cfg.auth.root_secret_key = Some(sk.clone());
    let problems = cfg.validate();
    anyhow::ensure!(
        problems.is_empty(),
        "invalid settings: {}",
        problems.join("; ")
    );
    let text = format!(
        "# Cairn configuration generated by `cairn init`. Keep this file private: it holds the\n# root secret. Every key can be overridden with CAIRN_<SECTION>_<FIELD>.\n\n{}",
        toml::to_string_pretty(&cfg)?
    );
    cairn_server::write_private(&cfg_path, text.as_bytes())
        .with_context(|| format!("writing {}", cfg_path.display()))?;
    cairn_server::load_or_create_master_key(&cfg.master_key_path())?;
    println!("Initialised {}", data_dir.display());
    println!("Config:     {}", cfg_path.display());
    if generated {
        println!();
        println!("Root credentials (shown once; also stored in the config file):");
        println!("  access key: {ak}");
        println!("  secret key: {sk}");
    }
    println!();
    println!(
        "Start the server with: cairn serve --config {}",
        cfg_path.display()
    );
    Ok(cfg_path)
}

fn load(path: Option<&Path>) -> anyhow::Result<Config> {
    if let Some(p) = path {
        anyhow::ensure!(p.exists(), "config file {} not found", p.display());
    }
    Config::load(path).context("loading configuration")
}

fn main() -> anyhow::Result<()> {
    let cli = Cli::parse();
    match cli.cmd {
        Cmd::Init { data_dir, listen } => {
            init(&data_dir, &listen)?;
            Ok(())
        }
        Cmd::Config {
            cmd: ConfigCmd::Check { config },
        } => {
            let cfg = load(config.as_deref())?;
            print!("{}", cfg.to_redacted_toml());
            let problems = cfg.validate();
            if problems.is_empty() {
                eprintln!("configuration OK");
                Ok(())
            } else {
                for p in &problems {
                    eprintln!("error: {p}");
                }
                anyhow::bail!("{} configuration problem(s)", problems.len())
            }
        }
        Cmd::Serve { config } => {
            let cfg = load(config.as_deref())?;
            let format = if cfg.log.json {
                LogFormat::Json
            } else {
                cli.log_format
            };
            init_tracing(format, &cfg.log.level);
            let rt = tokio::runtime::Builder::new_multi_thread()
                .enable_all()
                .thread_name("cairn")
                .build()?;
            rt.block_on(async move {
                let server = cairn_server::Server::bind(cfg).await?;
                server.run().await
            })
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn init_writes_valid_private_config() {
        let d = tempfile::tempdir().unwrap();
        let data = d.path().join("data");
        let p = init(&data, "127.0.0.1:0").unwrap();
        let cfg = Config::load(Some(&p)).unwrap();
        assert!(cfg.validate().is_empty(), "{:?}", cfg.validate());
        assert!(cfg.auth.root_access_key.unwrap().starts_with("CAIRN"));
        assert_eq!(cfg.auth.root_secret_key.unwrap().len(), 40);
        for sub in ["meta", "blobs", "tmp", "keys/master.key"] {
            assert!(data.join(sub).exists(), "{sub}");
        }
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt as _;
            let mode = std::fs::metadata(&p).unwrap().permissions().mode();
            assert_eq!(mode & 0o077, 0, "config must not be group/world readable");
        }
        assert!(
            init(&data, "127.0.0.1:0").is_err(),
            "init must not overwrite"
        );
    }
}
