"""Gate a ceph/s3-tests junit report on expected-pass.txt.

Usage:
  python3 -I compare.py junit.xml expected-pass.txt report_dir          # gate
  python3 -I compare.py --write junit.xml expected-pass.txt report_dir  # (re)write the baseline

Gate mode exits 1 if any test listed in expected-pass.txt did not pass (a regression, or a test
that disappeared from the selection). Tests that pass but are not listed are reported as
"promote" candidates and never fail the run. Writes report_dir/summary.md, passed.txt,
failed.txt and new-passes.txt.
"""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path


def test_id(case):
    cls = case.get("classname", "")
    mod = cls.split(".")[-1] if cls else ""
    return f"{mod}::{case.get('name')}" if mod else case.get("name")


def read_list(path):
    out = set()
    p = Path(path)
    if not p.exists():
        return out
    for line in p.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            out.add(line)
    return out


def main(argv):
    write = argv and argv[0] == "--write"
    if write:
        argv = argv[1:]
    junit, expected_path, out_dir = argv[:3]
    root = ET.parse(junit).getroot()
    passed, failed, skipped = set(), set(), set()
    for case in root.iter("testcase"):
        tid = test_id(case)
        if case.find("failure") is not None or case.find("error") is not None:
            failed.add(tid)
        elif case.find("skipped") is not None:
            skipped.add(tid)
        else:
            passed.add(tid)
    ran = len(passed) + len(failed)
    rate = 100.0 * len(passed) / ran if ran else 0.0
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "passed.txt").write_text("".join(f"{t}\n" for t in sorted(passed)))
    (out / "failed.txt").write_text("".join(f"{t}\n" for t in sorted(failed)))

    if write:
        if not passed:
            print("refusing to write an empty expected-pass.txt (nothing passed)", file=sys.stderr)
            return 2
        header = (
            "# ceph/s3-tests cases that pass against Cairn; CI fails if any of them stops passing.\n"
            "# Generated by `scripts/s3-tests/run.sh --write-expected` (compare.py --write).\n"
            "# Only add lines (promote new passes); removing one needs a reason in the commit.\n"
            f"# Baseline: {len(passed)} passed of {ran} executed ({rate:.1f}%), {len(skipped)} skipped.\n"
        )
        Path(expected_path).write_text(header + "".join(f"{t}\n" for t in sorted(passed)))
        print(f"wrote {len(passed)} ids to {expected_path} ({rate:.1f}% of {ran} executed)")
        return 0

    expected = read_list(expected_path)
    regressed = sorted(expected - passed)
    new = sorted(passed - expected)
    (out / "new-passes.txt").write_text("".join(f"{t}\n" for t in new))
    summary = [
        "# s3-tests summary",
        "",
        f"- passed: {len(passed)}",
        f"- failed: {len(failed)}",
        f"- skipped: {len(skipped)}",
        f"- pass rate: {rate:.1f}% of {ran} executed",
        f"- expected to pass: {len(expected)}; regressed or missing: {len(regressed)}",
        "",
        "## Regressions (listed in expected-pass.txt, did not pass)",
        *([f"- `{t}`" for t in regressed] or ["none"]),
        "",
        "## New passes (promote into expected-pass.txt)",
        *([f"- `{t}`" for t in new] or ["none"]),
        "",
    ]
    (out / "summary.md").write_text("\n".join(summary))
    print("\n".join(summary))
    return 1 if regressed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
